"""
SCRIPT 07: WORKFLOW ORCHESTRATION (MASTER EXECUTOR)

Purpose
-------
Provide a single entry point to run the consolidated ICESat-2 workflow.
This script executes Scripts 00–06 in sequence, manages run state,
and allows resuming from a failed step.

Origin / Consolidation
----------------------
- Consolidates:
  - 11_run_all.py
  - 12_run_partial.py

Main Tasks
----------
- Define the ordered list of processing scripts:
  00_setup_validation.py
  01_filter_photons.py
  02_filter_terrain.py
  03_analysis_core.py
  04_analysis_spatial.py
  05_analysis_temporal.py
  06_analysis_advanced.py
  07_output_generation.py
- Execute each script as a subprocess in order.
- Record status (SUCCESS / FAILED / TIMEOUT) and wall-clock time per
  script.
- Maintain a JSON state file (e.g. workflow_execution_state.json)
  with:
  - last_completed
  - last_failed
  - execution history.
- Support command-line options such as:
  - --start  : begin from a given script number
  - --resume : resume from last_failed
  - --status : print current execution state
  - --dry-run: show plan without executing.
- Write a processing log summarizing the run.

Inputs
------
- No direct data inputs; orchestrates other scripts.
- Reads configuration (paths etc.) shared with other scripts.

Outputs
-------
- workflow_execution_state.json
- processing_log_<RUN_ID>.txt
- All data and figures generated by Scripts 00–06.

Reproducibility Notes
---------------------
Always run the full pipeline via this script for production runs. The
execution log and state file are key artefacts for demonstrating that
results were produced in a single, documented run and can be reproduced
from the same code and inputs.
"""

import subprocess
import sys
import time
import warnings
import argparse
from datetime import datetime
from pathlib import Path

warnings.filterwarnings('ignore')

# ============================================================================
# PARSE COMMAND-LINE ARGUMENTS
# ============================================================================

parser = argparse.ArgumentParser(
    description="ICESat-2 Complete Analysis Workflow with Temporal Filtering"
)
parser.add_argument(
    '--temporal',
    type=str,
    choices=['1', '2', '3', '4'],
    default='2',
    help='Temporal filtering: 1=June-Oct, 2=June-Sept (default), 3=Early vs Late, 4=Same-month-only'
)
args = parser.parse_args()

TEMPORAL_OPTION = args.temporal

TEMPORAL_OPTIONS = {
    '1': 'June-October (Broad summer window)',
    '2': 'June-September (Standard thaw season)',
    '3': 'Early vs Late Summer (June-July vs Aug-Sept)',
    '4': 'Same-month-only (Strictest)',
}

# ============================================================================
# CONFIGURATION
# ============================================================================

BASE_OUTPUT_DIR = Path(r'E:\Processing\ICeSat-2\output_data')

# Define ALL scripts in execution order
# Format: (script_num, script_name, description, args, is_required)
SCRIPTS = [
    ('00', '00_setup_validation.py', 'Setup & validation', [], False),
    ('01', '01_filter_photons.py', 'Photon filtering (strong beams)', [], True),
    ('02', '02_filter_terrain.py', 'Terrain classification (land/ocean/lakes)', [], True),
    ('03', '03_analysis_core.py', 'Crossover analysis & InSAR integration', ['--temporal', TEMPORAL_OPTION], True),
    ('04', '04_analysis_spatial.py', 'Spatial analysis', [], True),
    ('05', '05_analysis_temporal.py', 'Temporal analysis', [], True),
    ('05b', '05b_temporal_stratification.py', 'Temporal stratification (seasonal)', [], False),
    ('06', '06_analysis_advanced.py', 'Advanced analysis', [], False),
    ('07', '07_output_generation.py', 'Output generation (figures + GIS)', [], True),
]

print("=" * 80)
print("ICESat-2 COMPLETE ANALYSIS PIPELINE")
print("=" * 80)
print(f"\nStart time: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
print(f"Temporal option: {TEMPORAL_OPTION} - {TEMPORAL_OPTIONS[TEMPORAL_OPTION]}")
print(f"Total scripts: {len(SCRIPTS)}")
print("=" * 80)

# ============================================================================
# RUN SCRIPTS
# ============================================================================

results = {}
start_time = time.time()

for script_num, script_name, description, script_args, is_required in SCRIPTS:
    print(f"\n[{script_num}] {description}")
    print(f"Script: {script_name}")
    if script_args:
        print(f"Arguments: {' '.join(script_args)}")
    print("-" * 80)

    script_start = time.time()

    # Check if script exists
    script_path = Path(script_name)
    if not script_path.exists():
        script_time = time.time() - script_start
        if is_required:
            print(f"✗ [{script_num}] REQUIRED script not found: {script_name}")
            results[script_num] = ('FAILED', script_time)
        else:
            print(f"⊘ [{script_num}] Optional script skipped (not found): {script_name}")
            results[script_num] = ('SKIPPED', script_time)
        continue

    try:
        # Build command
        cmd = [sys.executable, script_name] + script_args

        # Run script with real-time output
        result = subprocess.run(
            cmd,
            capture_output=False,
            text=True,
            check=False
        )

        script_time = time.time() - script_start

        if result.returncode == 0:
            print(f"\n✓ [{script_num}] Completed in {script_time:.1f}s")
            results[script_num] = ('SUCCESS', script_time)

        else:
            print(f"\n✗ [{script_num}] FAILED with exit code {result.returncode}")
            results[script_num] = ('FAILED', script_time)

    except Exception as e:
        script_time = time.time() - script_start
        print(f"\n✗ [{script_num}] ERROR: {str(e)}")
        results[script_num] = ('ERROR', script_time)

# ============================================================================
# EXECUTION SUMMARY
# ============================================================================

total_time = time.time() - start_time

print("\n" + "=" * 80)
print("PIPELINE EXECUTION SUMMARY")
print("=" * 80)
print(f"\nTotal time: {total_time / 60:.1f} minutes ({total_time:.0f} seconds)")
print("-" * 80)
print(f"{'Script':<8} {'Status':<12} {'Duration (s)':<15} {'Description'}")
print("-" * 80)

for script_num, script_name, description, _, is_required in SCRIPTS:
    if script_num in results:
        status, duration = results[script_num]
        if status == 'SUCCESS':
            status_symbol = "✓"
        elif status == 'SKIPPED':
            status_symbol = "⊘"
        else:
            status_symbol = "✗"
        print(f"{script_num:<8} {status:<12} {duration:<15.1f} {status_symbol} {description}")

print("=" * 80)

# ============================================================================
# STATISTICS
# ============================================================================

success_count = sum(1 for status, _ in results.values() if status == 'SUCCESS')
failed_count = sum(1 for status, _ in results.values() if status == 'FAILED')
error_count = sum(1 for status, _ in results.values() if status == 'ERROR')
skipped_count = sum(1 for status, _ in results.values() if status == 'SKIPPED')

print(f"\nResults Summary:")
print(f"  ✓ Successful: {success_count}/{len(SCRIPTS)}")
print(f"  ✗ Failed: {failed_count}/{len(SCRIPTS)}")
print(f"  ⊘ Skipped (optional): {skipped_count}/{len(SCRIPTS)}")
if error_count > 0:
    print(f"  ⚠ Errors: {error_count}/{len(SCRIPTS)}")

# Check for required script failures
required_scripts = [s for s in SCRIPTS if s[4]]  # is_required=True
required_failed = sum(1 for script_num, _, _, _, is_req in required_scripts 
                     if is_req and script_num in results and results[script_num][0] not in ['SUCCESS'])

if required_failed > 0:
    print(f"\n⚠ WARNING: {required_failed} required script(s) did not complete successfully")
    print("Workflow may not have full results")
elif failed_count > 0:
    print(f"\n⚠ Note: {failed_count} optional script(s) were skipped or failed")
    print("Core workflow completed successfully")
else:
    print("\n✓ All scripts completed successfully!")

# ============================================================================
# SAVE EXECUTION LOG
# ============================================================================

timestamp_file = BASE_OUTPUT_DIR / 'latest_run_timestamp.txt'

if timestamp_file.exists():
    with open(timestamp_file, 'r') as f:
        run_id = f.read().strip()

    log_dir = BASE_OUTPUT_DIR / f'run_{run_id}'
    log_file = log_dir / f'execution_log_{run_id}.txt'

    try:
        with open(log_file, 'w', encoding='utf-8') as f:
            f.write("=" * 80 + "\n")
            f.write("ICESat-2 Complete Analysis Pipeline - Execution Log\n")
            f.write("=" * 80 + "\n\n")
            f.write(f"Run ID: {run_id}\n")
            f.write(f"Start time: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n")
            f.write(f"Temporal option: {TEMPORAL_OPTION} - {TEMPORAL_OPTIONS[TEMPORAL_OPTION]}\n")
            f.write(f"Total time: {total_time / 60:.1f} minutes\n")
            f.write(f"Success: {success_count}/{len(SCRIPTS)}\n")
            f.write(f"Failed: {failed_count}/{len(SCRIPTS)}\n")
            f.write(f"Skipped: {skipped_count}/{len(SCRIPTS)}\n")
            f.write("=" * 80 + "\n\n")

            for script_num, script_name, description, script_args, is_required in SCRIPTS:
                if script_num in results:
                    status, duration = results[script_num]
                    required_str = "(Required)" if is_required else "(Optional)"
                    f.write(f"[{script_num}] {description} {required_str}\n")
                    f.write(f"  Script: {script_name}\n")
                    if script_args:
                        f.write(f"  Arguments: {' '.join(script_args)}\n")
                    f.write(f"  Status: {status}\n")
                    f.write(f"  Duration: {duration:.1f}s\n\n")

            f.write("=" * 80 + "\n")
            f.write("END OF LOG\n")
            f.write("=" * 80 + "\n")

        print(f"\nLog saved: {log_file}")

    except Exception as e:
        print(f"\nWarning: Could not save log file: {e}")

print("\n" + "=" * 80)
print("Workflow complete!")
print("=" * 80 + "\n")

# Exit with appropriate code
if required_failed > 0:
    sys.exit(1)
else:
    sys.exit(0)